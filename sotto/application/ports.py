"""Порты — то, что сценариям нужно от внешнего мира. Реализации лежат в infrastructure/.

Сценарии (application/) зависят только от домена и этих протоколов. Поэтому:
  • SQL, HTTP, CLI-агенты и процессы ОС можно заменить, не трогая сценарии;
  • новая ОС = новая реализация Platform (см. infrastructure/platform/), остальное не меняется;
  • в тестах подставляются простые заглушки.
"""

from __future__ import annotations

from collections.abc import AsyncIterator, Callable, Iterable
from pathlib import Path
from typing import Any, Protocol

import numpy as np

from ..domain.calls import Call
from ..domain.interviews import Interview
from ..domain.legend import LegendItem

# --- события для оверлея и сайта ---


class Events(Protocol):
    def publish(self, kind: str, data: dict[str, Any] | None = None) -> None: ...


# --- модели ---


class Completion(Protocol):
    text: str
    model: str
    first_token_ms: int | None
    total_ms: int | None
    cost: float | None


class LLM(Protocol):
    """Языковая модель по API (OpenRouter или прямой провайдер): подсказки, распознавание, интервьюер."""
    configured: bool

    async def chat(self, model: str, messages: list[dict], **kw: Any) -> Completion: ...
    def stream_chat(self, model: str, messages: list[dict], **kw: Any) -> AsyncIterator[tuple[str, Completion]]: ...
    async def transcribe(self, model: str, samples: np.ndarray) -> tuple[str, str | None, float | None]: ...


class AgentError(RuntimeError):
    """Ни один CLI-агент не справился."""


class LLMError(RuntimeError):
    """Модель по API не ответила (нет ключа, лимит, сеть)."""


class Agents(Protocol):
    """CLI-агенты (claude, codex…) для фоновых задач: итоги, брифы, разборы, темы."""
    async def run(self, prompt: str, *, prefer: str | None = None, task: str = "") -> tuple[str, str]: ...
    async def run_json(self, prompt: str, *, prefer: str | None = None, task: str = "") -> tuple[Any, str]: ...
    def status(self) -> list[dict[str, Any]]: ...


class Prompts(Protocol):
    """Промпты (встроенные и свои) и профиль кандидата."""
    def load(self, kind: str) -> str: ...
    def profile(self) -> str: ...


class SearchIndex(Protocol):
    def index_call(self, call_id: int) -> None: ...
    def remove(self, kind: str, ids: list[int]) -> None: ...


# --- хранилище ---


class Meta(Protocol):
    def get_meta(self, key: str, default: str | None = None) -> str | None: ...
    def set_meta(self, key: str, value: str) -> None: ...


class CallRepository(Protocol):
    def get(self, call_id: int) -> Call | None: ...
    def start(self, app: str, record_only: bool = False, **values: Any) -> int: ...
    def update(self, call_id: int, **values: Any) -> None: ...
    def delete(self, call_id: int) -> list[int]: ...
    def set_company(self, call_id: int, company: str | None, interview_id: int | None = None) -> None: ...
    def unlink_interview(self, interview_id: int) -> None: ...
    def for_interview(self, iv: Interview) -> list[Call]: ...
    def by_ids(self, ids: Iterable[int]) -> dict[int, Call]: ...
    def unfinished_since(self, since: float, min_utterances: int) -> list[int]: ...
    def transcript(self, call_id: int, since: float = 0.0) -> list[dict[str, Any]]: ...
    def hints(self, call_id: int) -> list[dict[str, Any]]: ...
    def add_utterance(self, **values: Any) -> int: ...
    def recent_them(self, call_id: int, after: float, limit: int = 3) -> list[str]: ...
    def add_answer(self, **values: Any) -> int: ...
    def add_speaker(self, call_id: int, label: str, is_me: bool = False, embedding: bytes | None = None,
                    name: str | None = None) -> int: ...
    def speaker(self, speaker_id: int) -> dict[str, Any] | None: ...
    def other_speakers(self, call_id: int) -> list[int]: ...
    def rename_speaker(self, speaker_id: int, name: str | None, role: str | None) -> None: ...
    def name_speaker(self, speaker_id: int, name: str) -> None: ...


class LegendRepository(Protocol):
    def all(self) -> list[LegendItem]: ...
    def add(self, claim: str, *, note: str | None = None, company: str | None = None,
            call_id: int | None = None, answer_id: int | None = None) -> int: ...
    def get(self, item_id: int) -> LegendItem | None: ...
    def save(self, item: LegendItem) -> None: ...
    def delete(self, ids: Iterable[int]) -> None: ...
    def move_call(self, call_id: int, company: str | None) -> None: ...
    def delete_company(self, company: str) -> None: ...


class InterviewRepository(Protocol):
    def get(self, iid: int) -> Interview | None: ...
    def all(self) -> list[Interview]: ...
    def add(self, iv: Interview) -> int: ...
    def save(self, iv: Interview) -> None: ...
    def delete(self, iid: int) -> None: ...


class TrainerRepository(Protocol):
    def topics(self, kind: str, limit: int = 60) -> list[dict[str, Any]]: ...
    def raw_signals(self, kind: str, limit: int = 80) -> list[str]: ...
    def by_score(self, kind: str, weak: bool, limit: int) -> list[str]: ...
    def add_items(self, kind: str, items: Iterable[str], source: str, due_at: float, bump: bool = False) -> None: ...
    def replace_agent_topics(self, kind: str, topics: list[str], now: float) -> None: ...
    def item(self, kind: str, text: str) -> dict[str, Any] | None: ...
    def update_item(self, item_id: int, **values: Any) -> None: ...
    def delete_item(self, item_id: int) -> None: ...
    def start_session(self, kind: str, topic: str, now: float) -> int: ...
    def add_turn(self, session_id: int, role: str, text: str, now: float) -> int: ...
    def set_last_feedback(self, session_id: int, feedback: str) -> None: ...
    def finish_session(self, session_id: int, now: float, feedback: str | None) -> None: ...


class RecordingRepository(Protocol):
    def get(self, rec_id: int) -> dict[str, Any] | None: ...
    def open(self, path: str, started_at: float, fps: int) -> int: ...
    def close(self, rec_id: int, path: str, ended_at: float, size: int) -> None: ...
    def delete(self, rec_id: int) -> None: ...
    def unfinished(self) -> list[dict[str, Any]]: ...


# --- платформа (ОС и рабочий стол) ---


ChunkCallback = Callable[[str, np.ndarray, float], None]   # канал, отсчёты float32 16 кГц, время начала


class Process(Protocol):
    def poll(self) -> int | None: ...
    def wait(self, timeout: float | None = None) -> int: ...
    def terminate(self) -> None: ...


class AudioInput(Protocol):
    """Два потока: "me" — микрофон, "them" — всё, что слышишь (выход системы)."""
    def start(self) -> None: ...
    def stop(self) -> None: ...


class VideoSegment(Protocol):
    """Запись экрана в файл, пока не закроют."""
    def alive(self) -> bool: ...
    def close(self) -> None: ...


class WindowManager(Protocol):
    """Окна рабочего стола: оверлей, скрытый из демонстрации экрана, глобальные хоткеи, «сцена»."""
    def available(self) -> bool: ...
    def protect_overlay(self, x: int, y: int, w: int, h: int) -> bool: ...
    def overlay_window(self) -> str | None: ...
    def is_protected(self, window: str) -> bool: ...
    def protect(self, window: str) -> None: ...
    def overlay_geometry(self) -> tuple[int, int, int, int] | None: ...
    def default_overlay_position(self, width: int) -> tuple[int, int]: ...
    def focus(self, window: str) -> None: ...
    def bind_hotkeys(self, binds: dict[str, str], command: str) -> list[str]:
        """Регистрирует хоткеи; возвращает сочетания, занятые чем-то другим (их не трогает)."""
        ...
    def unbind_hotkeys(self, keys: list[str]) -> None: ...
    def listen(self, on_focus: Callable[[str], None], on_reload: Callable[[], None], stop: Any) -> None: ...
    def stage_active(self) -> bool: ...
    def stage_on(self) -> str: ...
    def stage_off(self) -> str: ...
    stage_name: str


class Platform(Protocol):
    """Всё, что зависит от ОС. Linux/Hyprland — infrastructure/platform/linux; без рабочего стола — null."""
    name: str
    wm: WindowManager

    def audio_input(self, mic: str, system: str, on_chunk: ChunkCallback) -> AudioInput: ...
    def microphone_users(self, ignore: list[str]) -> list[str]: ...
    def play(self, samples: np.ndarray, sample_rate: int, target: str | None = None) -> Process: ...
    def screen_locked(self) -> bool: ...
    def screenshot(self, dest: Path, output: str | None = None, region: bool = False) -> Path | None: ...
    def focused_output(self) -> str: ...
    def active_window(self) -> dict[str, Any]: ...
    def notify(self, title: str, text: str) -> None: ...
    def open_media(self, path: Path, offset_s: float = 0) -> None: ...
    def clipboard(self) -> str: ...
    def copy_text(self, text: str) -> None: ...
    def video_available(self) -> bool: ...
    def record_screen(self, path: Path, fps: int, output: str, settings: Any) -> VideoSegment: ...
